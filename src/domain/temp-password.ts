const DIGITS = 4;

/** Returns an integer in [0, max); crypto-strong by default. */
export type RandomInt = (max: number) => number;

/**
 * A one-time password like `giao-7342`: one word and 4 digits, about 21 bits.
 * Enough because it only lives until the first sign-in, and five wrong tries
 * lock the login name for 15 minutes (design D2, D3).
 */
export function generateTempPassword(random: RandomInt = randomInt): string {
  const word = TEMP_PASSWORD_WORDS[random(TEMP_PASSWORD_WORDS.length)];
  if (word === undefined) {
    throw new RangeError("random() returned an index outside the word list");
  }
  const digits = String(random(10 ** DIGITS)).padStart(DIGITS, "0");
  return `${word}-${digits}`;
}
